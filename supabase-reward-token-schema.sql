-- Driacom Rewarded Ads / Bonus Token
-- Jalankan sekali di Supabase SQL Editor.
create table if not exists public.prompt_bonus_tokens (
  user_id uuid primary key references auth.users(id) on delete cascade,
  tokens integer not null default 0 check (tokens >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.rewarded_ad_claims (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  reward_date date not null,
  ads_completed integer not null default 2,
  created_at timestamptz not null default now(),
  unique(user_id, reward_date)
);

create or replace function public.consume_prompt_bonus_token(p_user_id uuid)
returns boolean
language plpgsql
security definer
as $$
declare current_tokens integer;
begin
  select tokens into current_tokens from public.prompt_bonus_tokens where user_id = p_user_id for update;
  if coalesce(current_tokens, 0) <= 0 then return false; end if;
  update public.prompt_bonus_tokens set tokens = current_tokens - 1, updated_at = now() where user_id = p_user_id;
  return true;
end;
$$;

grant execute on function public.consume_prompt_bonus_token(uuid) to service_role;
